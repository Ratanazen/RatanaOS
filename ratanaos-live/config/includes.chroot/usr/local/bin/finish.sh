#!/usr/bin/env bash
# ==============================================================================
# RatanaOS Installer: fstab Generation & Finalization Module
# ==============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${SCRIPT_DIR}/filesystem.sh"

generate_fstab() {
    local dev="$1"
    local target_mount="${2:-/mnt/target}"
    local mode="${3:-auto}"

    if [ "$mode" = "auto" ]; then
        if [ -d "/sys/firmware/efi" ]; then
            mode="uefi"
        else
            mode="bios"
        fi
    fi

    echo "==> Generating /etc/fstab with persistent filesystem UUIDs..."

    local part_root part_esp="" root_uuid esp_uuid=""
    if [ "$mode" = "uefi" ]; then
        part_esp=$(get_part_device "$dev" 1)
        part_root=$(get_part_device "$dev" 2)
        esp_uuid=$(blkid -s UUID -o value "$part_esp" || true)
    else
        part_root=$(get_part_device "$dev" 1)
    fi

    root_uuid=$(blkid -s UUID -o value "$part_root" || true)

    if [ -z "$root_uuid" ]; then
        echo "Error: Unable to retrieve UUID for root partition $part_root" >&2
        return 1
    fi

    cat << FEOF > "${target_mount}/etc/fstab"
# /etc/fstab: static file system information.
# Generated by RatanaOS Master Installer on $(date -u)
# <file system>                             <mount point>   <type>  <options>               <dump>  <pass>

# Root filesystem
UUID=${root_uuid}    /               ext4    errors=remount-ro,noatime 0       1
FEOF

    if [ "$mode" = "uefi" ] && [ -n "$esp_uuid" ]; then
        cat << EEOF >> "${target_mount}/etc/fstab"
# EFI System Partition
UUID=${esp_uuid}    /boot/efi       vfat    umask=0077              0       1
EEOF
    fi

    # tmpfs
    cat << TEOF >> "${target_mount}/etc/fstab"
# Temporary directories
tmpfs                                       /tmp            tmpfs   defaults,nosuid,nodev   0       0
TEOF

    echo "fstab generated successfully at ${target_mount}/etc/fstab."
}

finish_installation() {
    local target_mount="${1:-/mnt/target}"
    echo "==> Finalizing installation and syncing disk caches..."
    sync

    unmount_target "$target_mount"

    echo ""
    echo "============================================================"
    echo " 🎉 RatanaOS INSTALLATION COMPLETED SUCCESSFULLY!"
    echo "============================================================"
    echo "  You can now reboot your computer."
    echo "  Please remove the Live USB installation medium."
    echo "  The system will boot directly from your internal disk."
    echo "============================================================"
}

if [ "${BASH_SOURCE[0]}" = "${0}" ]; then
    if [ $# -lt 1 ]; then
        echo "Usage: $0 <target-disk> [target-mount] [auto|uefi|bios]"
        exit 1
    fi
    generate_fstab "$1" "${2:-/mnt/target}" "${3:-auto}"
    finish_installation "${2:-/mnt/target}"
fi
